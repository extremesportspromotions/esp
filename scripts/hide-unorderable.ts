/**
 * Build-time shop safeguard. Uses the same checkout acceptance rules as src/lib/shop.ts,
 * writes a client-safe hide list (no design numbers), and logs a warning.
 * Hidden items do not fail the build.
 */
import Module from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const orig = (Module as unknown as { _load: (request: string, parent: unknown, isMain: boolean) => unknown })._load;
(Module as unknown as { _load: typeof orig })._load = function (request, parent, isMain) {
  if (request === "server-only") return {};
  return orig.call(this, request, parent, isMain);
};

async function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const { hiddenFromCheckout, formatHiddenWarning } = await import("../src/lib/shopVisibility");
  const hidden = hiddenFromCheckout();
  console.warn(formatHiddenWarning(hidden));
  const body = hidden.colours
    .map((c) => `  { key: ${JSON.stringify(c.key)}, name: ${JSON.stringify(c.name)}, colour: ${JSON.stringify(c.colour)} },`)
    .join("\n");
  const file = `/** Auto-generated by scripts/hide-unorderable.ts from checkout rules. Do not edit. */
export const hiddenColours: { key: string; name: string; colour: string }[] = [
${body}
];
`;
  writeFileSync(join(root, "src/components/shop/hiddenFromShop.ts"), file);
}

main().catch((err: unknown) => {
  console.warn("Shop visibility check did not run:", err instanceof Error ? err.message : err);
  process.exit(0);
});
